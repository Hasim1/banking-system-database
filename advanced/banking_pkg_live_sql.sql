-- 1.1 Customers
CREATE TABLE customers (
   customer_id       NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
   full_name         VARCHAR2(100) NOT NULL,
   phone_number      VARCHAR2(20),
   email             VARCHAR2(100) UNIQUE,
   registration_date DATE DEFAULT SYSDATE NOT NULL
);

-- 1.2 Accounts
--     status          : business state of the account (ACTIVE / FROZEN / CLOSED)
--     version_number  : OPTIMISTIC concurrency control - bumped on every UPDATE
--     updated_at      : maintained automatically by a BEFORE-UPDATE trigger
CREATE TABLE accounts (
   account_id     NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
   customer_id    NUMBER NOT NULL,
   account_type   VARCHAR2(20) NOT NULL,
   balance        NUMBER(15,2) DEFAULT 0 NOT NULL,
   currency       VARCHAR2(10) DEFAULT 'USD' NOT NULL,
   status         VARCHAR2(10) DEFAULT 'ACTIVE' NOT NULL,
   version_number NUMBER       DEFAULT 0 NOT NULL,
   created_at     TIMESTAMP    DEFAULT SYSTIMESTAMP NOT NULL,
   updated_at     TIMESTAMP    DEFAULT SYSTIMESTAMP NOT NULL,
   CONSTRAINT fk_account_customer FOREIGN KEY (customer_id) REFERENCES customers(customer_id),
   CONSTRAINT chk_acc_balance CHECK (balance >= 0),
   CONSTRAINT chk_acc_type    CHECK (account_type IN ('CHECKING','SAVINGS','CREDIT','LOAN')),
   CONSTRAINT chk_acc_status  CHECK (status IN ('ACTIVE','FROZEN','CLOSED'))
);

-- 1.3 Transactions (immutable financial ledger)
--     balance_after        : running balance snapshot for statements/auditing
--     transfer_ref         : links the two legs of a transfer (OUT + IN)
--     counterparty_account : the other side of a transfer
CREATE TABLE transactions (
   transaction_id       NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
   account_id           NUMBER NOT NULL,
   transaction_type     VARCHAR2(20) NOT NULL,
   amount               NUMBER(15,2) NOT NULL,
   balance_after        NUMBER(15,2),
   status               VARCHAR2(15) DEFAULT 'COMPLETED' NOT NULL,
   transfer_ref         VARCHAR2(40),
   counterparty_account NUMBER,
   transaction_date     TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
   CONSTRAINT fk_txn_account FOREIGN KEY (account_id) REFERENCES accounts(account_id),
   CONSTRAINT chk_txn_amount CHECK (amount > 0),
   CONSTRAINT chk_txn_type   CHECK (transaction_type IN
                  ('OPENING','DEPOSIT','WITHDRAWAL','TRANSFER_IN','TRANSFER_OUT')),
   CONSTRAINT chk_txn_status CHECK (status IN ('PENDING','COMPLETED','FAILED','REVERSED'))
);

-- 1.4 Audit log (the AUDIT TRAIL - populated by triggers, part of the main txn)
CREATE TABLE audit_log (
   audit_id    NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
   table_name  VARCHAR2(30) NOT NULL,
   action      VARCHAR2(20) NOT NULL,
   account_id  NUMBER,
   old_balance NUMBER(15,2),
   new_balance NUMBER(15,2),
   changed_by  VARCHAR2(50)  DEFAULT USER NOT NULL,
   changed_at  TIMESTAMP     DEFAULT SYSTIMESTAMP NOT NULL,
   details     VARCHAR2(400)
);

-- 1.5 Error log (written by an AUTONOMOUS transaction so it survives ROLLBACK)
CREATE TABLE error_log (
   error_id      NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
   module        VARCHAR2(40),
   account_id    NUMBER,
   error_code    NUMBER,
   error_message VARCHAR2(400),
   logged_by     VARCHAR2(50) DEFAULT USER NOT NULL,
   logged_at     TIMESTAMP    DEFAULT SYSTIMESTAMP NOT NULL
);

/* ----------------------------------------------------------------------------
   SECTION 2 — INDEXES (query optimization)
   ---------------------------------------------------------------------------- */
CREATE INDEX idx_accounts_customer ON accounts(customer_id);
CREATE INDEX idx_txn_account       ON transactions(account_id);
CREATE INDEX idx_txn_date          ON transactions(transaction_date);
CREATE INDEX idx_txn_ref           ON transactions(transfer_ref);

/* ----------------------------------------------------------------------------
   SECTION 3 — TRIGGERS (AUDIT TRAIL + auto-maintained columns)
   Audit triggers write only to AUDIT_LOG (a different table), so there is no
   "mutating table" conflict with the procedures that modify ACCOUNTS/TRANSACTIONS.
   ---------------------------------------------------------------------------- */

-- 3.1 Keep updated_at fresh and bump the optimistic-lock version on every change
CREATE OR REPLACE TRIGGER trg_accounts_biu
BEFORE UPDATE ON accounts
FOR EACH ROW
BEGIN
   :NEW.updated_at     := SYSTIMESTAMP;
   :NEW.version_number := NVL(:OLD.version_number, 0) + 1;
END;
/

-- 3.2 Record every balance/status change to the audit trail
CREATE OR REPLACE TRIGGER trg_accounts_aud
AFTER UPDATE ON accounts
FOR EACH ROW
BEGIN
   IF :OLD.balance <> :NEW.balance OR :OLD.status <> :NEW.status THEN
      INSERT INTO audit_log (table_name, action, account_id, old_balance, new_balance, details)
      VALUES ('ACCOUNTS', 'UPDATE', :NEW.account_id, :OLD.balance, :NEW.balance,
              'status ' || :OLD.status || '->' || :NEW.status ||
              ', version ' || :NEW.version_number);
   END IF;
END;
/

-- 3.3 Record every new ledger entry to the audit trail
CREATE OR REPLACE TRIGGER trg_transactions_aud
AFTER INSERT ON transactions
FOR EACH ROW
BEGIN
   INSERT INTO audit_log (table_name, action, account_id, new_balance, details)
   VALUES ('TRANSACTIONS', 'INSERT', :NEW.account_id, :NEW.balance_after,
           :NEW.transaction_type || ' amount ' || :NEW.amount ||
           CASE WHEN :NEW.transfer_ref IS NOT NULL
                THEN ' (ref ' || :NEW.transfer_ref || ')' ELSE '' END);
END;
/

/* ----------------------------------------------------------------------------
   SECTION 4 — BUSINESS LOGIC PACKAGE (BANKING_PKG)
   ---------------------------------------------------------------------------- */

-- 4.1 Specification
CREATE OR REPLACE PACKAGE banking_pkg AS
   PROCEDURE add_customer (p_full_name   IN  VARCHAR2,
                           p_phone       IN  VARCHAR2,
                           p_email       IN  VARCHAR2,
                           p_customer_id OUT NUMBER);

   PROCEDURE open_account (p_customer_id IN  NUMBER,
                           p_type        IN  VARCHAR2,
                           p_currency    IN  VARCHAR2 DEFAULT 'USD',
                           p_initial     IN  NUMBER   DEFAULT 0,
                           p_account_id  OUT NUMBER);

   PROCEDURE deposit  (p_account_id IN NUMBER, p_amount IN NUMBER);
   PROCEDURE withdraw (p_account_id IN NUMBER, p_amount IN NUMBER);
   PROCEDURE transfer (p_from_account IN NUMBER,
                       p_to_account   IN NUMBER,
                       p_amount       IN NUMBER);

   FUNCTION  get_balance (p_account_id IN NUMBER) RETURN NUMBER;
END banking_pkg;
/

-- 4.2 Body
CREATE OR REPLACE PACKAGE BODY banking_pkg AS

   /* Private: write an error row in its OWN transaction.
      AUTONOMOUS_TRANSACTION => the COMMIT here does not affect the caller's
      transaction, so the audit of the failure survives the caller's ROLLBACK. */
   PROCEDURE log_error (p_module     IN VARCHAR2,
                        p_account_id IN NUMBER,
                        p_message    IN VARCHAR2) IS
      PRAGMA AUTONOMOUS_TRANSACTION;
   BEGIN
      INSERT INTO error_log (module, account_id, error_code, error_message)
      VALUES (p_module, p_account_id, SQLCODE, p_message);
      COMMIT;
   END log_error;

   ----------------------------------------------------------------------------
   PROCEDURE add_customer (p_full_name   IN  VARCHAR2,
                           p_phone       IN  VARCHAR2,
                           p_email       IN  VARCHAR2,
                           p_customer_id OUT NUMBER) IS
   BEGIN
      INSERT INTO customers (full_name, phone_number, email)
      VALUES (p_full_name, p_phone, p_email)
      RETURNING customer_id INTO p_customer_id;
      COMMIT;
      DBMS_OUTPUT.PUT_LINE('Customer #' || p_customer_id || ' created: ' || p_full_name);
   EXCEPTION
      WHEN OTHERS THEN
         ROLLBACK;
         log_error('ADD_CUSTOMER', NULL, SQLERRM);
         RAISE;
   END add_customer;

   ----------------------------------------------------------------------------
   PROCEDURE open_account (p_customer_id IN  NUMBER,
                           p_type        IN  VARCHAR2,
                           p_currency    IN  VARCHAR2 DEFAULT 'USD',
                           p_initial     IN  NUMBER   DEFAULT 0,
                           p_account_id  OUT NUMBER) IS
   BEGIN
      IF p_initial < 0 THEN
         RAISE_APPLICATION_ERROR(-20001, 'Initial deposit cannot be negative.');
      END IF;

      INSERT INTO accounts (customer_id, account_type, balance, currency, status)
      VALUES (p_customer_id, p_type, p_initial, p_currency, 'ACTIVE')
      RETURNING account_id INTO p_account_id;

      IF p_initial > 0 THEN
         INSERT INTO transactions (account_id, transaction_type, amount, balance_after, status)
         VALUES (p_account_id, 'OPENING', p_initial, p_initial, 'COMPLETED');
      END IF;

      COMMIT;
      DBMS_OUTPUT.PUT_LINE('Opened ' || p_type || ' account #' || p_account_id ||
                           ' for customer #' || p_customer_id ||
                           ' (opening balance ' || p_initial || ' ' || p_currency || ')');
   EXCEPTION
      WHEN OTHERS THEN
         ROLLBACK;
         log_error('OPEN_ACCOUNT', NULL, SQLERRM);
         RAISE;
   END open_account;

   ----------------------------------------------------------------------------
   -- DEPOSIT: lock the row (FOR UPDATE), validate, update, ledger, COMMIT.
   ----------------------------------------------------------------------------
   PROCEDURE deposit (p_account_id IN NUMBER, p_amount IN NUMBER) IS
      v_balance accounts.balance%TYPE;
      v_status  accounts.status%TYPE;
   BEGIN
      IF p_amount <= 0 THEN
         RAISE_APPLICATION_ERROR(-20001, 'Deposit amount must be positive.');
      END IF;

      -- Pessimistic concurrency control: lock this account row until COMMIT
      SELECT balance, status INTO v_balance, v_status
        FROM accounts
       WHERE account_id = p_account_id
         FOR UPDATE;

      IF v_status <> 'ACTIVE' THEN
         RAISE_APPLICATION_ERROR(-20002, 'Account #' || p_account_id ||
                                          ' is not active (status=' || v_status || ').');
      END IF;

      v_balance := v_balance + p_amount;

      UPDATE accounts SET balance = v_balance WHERE account_id = p_account_id;

      INSERT INTO transactions (account_id, transaction_type, amount, balance_after, status)
      VALUES (p_account_id, 'DEPOSIT', p_amount, v_balance, 'COMPLETED');

      COMMIT;
      DBMS_OUTPUT.PUT_LINE('DEPOSIT  +' || p_amount || ' -> acct #' || p_account_id ||
                           ' | new balance ' || v_balance);
   EXCEPTION
      WHEN NO_DATA_FOUND THEN
         ROLLBACK;
         log_error('DEPOSIT', p_account_id, 'Account not found');
         RAISE_APPLICATION_ERROR(-20010, 'Account #' || p_account_id || ' not found.');
      WHEN OTHERS THEN
         ROLLBACK;
         log_error('DEPOSIT', p_account_id, SQLERRM);
         RAISE;
   END deposit;

   ----------------------------------------------------------------------------
   -- WITHDRAW: lock row, validate funds, update, ledger, COMMIT.
   ----------------------------------------------------------------------------
   PROCEDURE withdraw (p_account_id IN NUMBER, p_amount IN NUMBER) IS
      v_balance accounts.balance%TYPE;
      v_status  accounts.status%TYPE;
   BEGIN
      IF p_amount <= 0 THEN
         RAISE_APPLICATION_ERROR(-20001, 'Withdrawal amount must be positive.');
      END IF;

      SELECT balance, status INTO v_balance, v_status
        FROM accounts
       WHERE account_id = p_account_id
         FOR UPDATE;

      IF v_status <> 'ACTIVE' THEN
         RAISE_APPLICATION_ERROR(-20002, 'Account #' || p_account_id ||
                                          ' is not active (status=' || v_status || ').');
      END IF;

      IF v_balance < p_amount THEN
         RAISE_APPLICATION_ERROR(-20003, 'Insufficient funds in acct #' || p_account_id ||
                                          ' (balance ' || v_balance ||
                                          ', requested ' || p_amount || ').');
      END IF;

      v_balance := v_balance - p_amount;

      UPDATE accounts SET balance = v_balance WHERE account_id = p_account_id;

      INSERT INTO transactions (account_id, transaction_type, amount, balance_after, status)
      VALUES (p_account_id, 'WITHDRAWAL', p_amount, v_balance, 'COMPLETED');

      COMMIT;
      DBMS_OUTPUT.PUT_LINE('WITHDRAW -' || p_amount || ' -> acct #' || p_account_id ||
                           ' | new balance ' || v_balance);
   EXCEPTION
      WHEN NO_DATA_FOUND THEN
         ROLLBACK;
         log_error('WITHDRAW', p_account_id, 'Account not found');
         RAISE_APPLICATION_ERROR(-20010, 'Account #' || p_account_id || ' not found.');
      WHEN OTHERS THEN
         ROLLBACK;
         log_error('WITHDRAW', p_account_id, SQLERRM);
         RAISE;
   END withdraw;

   ----------------------------------------------------------------------------
   -- TRANSFER: the headline ACID operation.
   --   * Both legs succeed or BOTH are rolled back (atomicity).
   --   * Rows are locked in ascending account_id order to avoid deadlocks.
   --   * A shared transfer_ref ties the OUT and IN ledger entries together.
   ----------------------------------------------------------------------------
   PROCEDURE transfer (p_from_account IN NUMBER,
                       p_to_account   IN NUMBER,
                       p_amount       IN NUMBER) IS
      v_from_bal    accounts.balance%TYPE;
      v_to_bal      accounts.balance%TYPE;
      v_from_status accounts.status%TYPE;
      v_to_status   accounts.status%TYPE;
      v_ref         VARCHAR2(40) := 'TRF-' || SUBSTR(RAWTOHEX(SYS_GUID()), 1, 12);
   BEGIN
      IF p_amount <= 0 THEN
         RAISE_APPLICATION_ERROR(-20001, 'Transfer amount must be positive.');
      END IF;
      IF p_from_account = p_to_account THEN
         RAISE_APPLICATION_ERROR(-20004, 'Cannot transfer to the same account.');
      END IF;

      -- Deadlock-safe locking: the IN-list + ORDER BY locks rows in a
      -- deterministic (ascending account_id) order for every caller.
      FOR rec IN (SELECT account_id, balance, status
                    FROM accounts
                   WHERE account_id IN (p_from_account, p_to_account)
                   ORDER BY account_id
                     FOR UPDATE)
      LOOP
         IF rec.account_id = p_from_account THEN
            v_from_bal := rec.balance; v_from_status := rec.status;
         ELSE
            v_to_bal := rec.balance;   v_to_status := rec.status;
         END IF;
      END LOOP;

      IF v_from_status IS NULL THEN
         RAISE_APPLICATION_ERROR(-20010, 'Source account #' || p_from_account || ' not found.');
      END IF;
      IF v_to_status IS NULL THEN
         RAISE_APPLICATION_ERROR(-20010, 'Destination account #' || p_to_account || ' not found.');
      END IF;
      IF v_from_status <> 'ACTIVE' THEN
         RAISE_APPLICATION_ERROR(-20002, 'Source account #' || p_from_account || ' is not active.');
      END IF;
      IF v_to_status <> 'ACTIVE' THEN
         RAISE_APPLICATION_ERROR(-20002, 'Destination account #' || p_to_account || ' is not active.');
      END IF;
      IF v_from_bal < p_amount THEN
         RAISE_APPLICATION_ERROR(-20003, 'Insufficient funds in acct #' || p_from_account ||
                                          ' (balance ' || v_from_bal || ', requested ' || p_amount || ').');
      END IF;

      v_from_bal := v_from_bal - p_amount;
      v_to_bal   := v_to_bal   + p_amount;

      UPDATE accounts SET balance = v_from_bal WHERE account_id = p_from_account;
      UPDATE accounts SET balance = v_to_bal   WHERE account_id = p_to_account;

      INSERT INTO transactions (account_id, transaction_type, amount, balance_after,
                                status, transfer_ref, counterparty_account)
      VALUES (p_from_account, 'TRANSFER_OUT', p_amount, v_from_bal,
              'COMPLETED', v_ref, p_to_account);

      INSERT INTO transactions (account_id, transaction_type, amount, balance_after,
                                status, transfer_ref, counterparty_account)
      VALUES (p_to_account, 'TRANSFER_IN', p_amount, v_to_bal,
              'COMPLETED', v_ref, p_from_account);

      COMMIT;  -- atomic commit: both legs are now durable together
      DBMS_OUTPUT.PUT_LINE('TRANSFER ' || p_amount || ' from #' || p_from_account ||
                           ' to #' || p_to_account || ' | ref ' || v_ref ||
                           ' | balances ' || v_from_bal || ' / ' || v_to_bal);
   EXCEPTION
      WHEN OTHERS THEN
         ROLLBACK;  -- neither leg persists
         log_error('TRANSFER', p_from_account, SQLERRM);
         RAISE;
   END transfer;

   ----------------------------------------------------------------------------
   FUNCTION get_balance (p_account_id IN NUMBER) RETURN NUMBER IS
      v_balance accounts.balance%TYPE;
   BEGIN
      SELECT balance INTO v_balance FROM accounts WHERE account_id = p_account_id;
      RETURN v_balance;
   EXCEPTION
      WHEN NO_DATA_FOUND THEN
         RAISE_APPLICATION_ERROR(-20010, 'Account #' || p_account_id || ' not found.');
   END get_balance;

END banking_pkg;
/

/* ----------------------------------------------------------------------------
   SECTION 5 — DEMO  (proves every feature works end to end)
   ---------------------------------------------------------------------------- */
DECLARE
   v_cust1 NUMBER;
   v_cust2 NUMBER;
   v_acc1  NUMBER;
   v_acc2  NUMBER;
BEGIN
   DBMS_OUTPUT.PUT_LINE('===== BANKING SYSTEM DEMO =====');

   -- Setup
   banking_pkg.add_customer('Alice Johnson', '+1-555-0100', 'alice@example.com', v_cust1);
   banking_pkg.add_customer('Bob Smith',     '+1-555-0200', 'bob@example.com',   v_cust2);

   banking_pkg.open_account(v_cust1, 'CHECKING', 'USD', 1000, v_acc1);
   banking_pkg.open_account(v_cust2, 'SAVINGS',  'USD',  250, v_acc2);

   -- Happy-path operations
   banking_pkg.deposit (v_acc1, 500);   -- 1000 -> 1500
   banking_pkg.withdraw(v_acc1, 200);   -- 1500 -> 1300
   banking_pkg.transfer(v_acc1, v_acc2, 300);  -- acct1 1000, acct2 550

   DBMS_OUTPUT.PUT_LINE('Balance acct #' || v_acc1 || ' = ' || banking_pkg.get_balance(v_acc1));
   DBMS_OUTPUT.PUT_LINE('Balance acct #' || v_acc2 || ' = ' || banking_pkg.get_balance(v_acc2));

   -- Negative path: overdraft is rejected, the transaction is rolled back,
   -- and the failure is recorded in ERROR_LOG (autonomous transaction).
   DBMS_OUTPUT.PUT_LINE('--- Attempting an overdraft (should fail & roll back) ---');
   BEGIN
      banking_pkg.withdraw(v_acc2, 999999);
   EXCEPTION
      WHEN OTHERS THEN
         DBMS_OUTPUT.PUT_LINE('Expected failure caught: ' || SQLERRM);
   END;

   DBMS_OUTPUT.PUT_LINE('Balance acct #' || v_acc2 || ' is still ' ||
                        banking_pkg.get_balance(v_acc2) || ' (unchanged - ACID rollback worked)');
   DBMS_OUTPUT.PUT_LINE('===== DEMO COMPLETE =====');
END;
