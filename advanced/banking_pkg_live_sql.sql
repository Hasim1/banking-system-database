/* ----------------------------------------------------------------------------
   SECTION 7 — SHOWCASE QUERIES (good to highlight in the GitHub README)
   ---------------------------------------------------------------------------- */

-- 7.1 JOIN + aggregation: each customer's total holdings
SELECT c.customer_id,
       c.full_name,
       COUNT(a.account_id)        AS num_accounts,
       NVL(SUM(a.balance), 0)     AS total_balance
  FROM customers c
  LEFT JOIN accounts a ON a.customer_id = c.customer_id
 GROUP BY c.customer_id, c.full_name
 ORDER BY total_balance DESC;

-- 7.2 Analytic function: per-account running balance from the ledger
SELECT account_id,
       transaction_id,
       transaction_type,
       amount,
       SUM(CASE WHEN transaction_type IN ('WITHDRAWAL','TRANSFER_OUT')
                THEN -amount ELSE amount END)
           OVER (PARTITION BY account_id ORDER BY transaction_id) AS running_balance
  FROM transactions
 ORDER BY account_id, transaction_id;

-- 7.3 Subquery: accounts holding more than the average balance
SELECT account_id, customer_id, balance
  FROM accounts
 WHERE balance > (SELECT AVG(balance) FROM accounts)
 ORDER BY balance DESC;

-- 7.4 Reassemble both legs of every transfer via a self-join on transfer_ref
SELECT o.transfer_ref,
       o.account_id           AS from_account,
       i.account_id           AS to_account,
       o.amount,
       o.transaction_date
  FROM transactions o
  JOIN transactions i
    ON i.transfer_ref = o.transfer_ref
   AND i.transaction_type = 'TRANSFER_IN'
 WHERE o.transaction_type = 'TRANSFER_OUT'
 ORDER BY o.transaction_date;
