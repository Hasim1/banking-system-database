                'balance=' || :OLD.balance || '; status=' || :OLD.status,
                'balance=' || :NEW.balance || '; status=' || :NEW.status);
    ELSIF DELETING THEN
        INSERT INTO audit_logs (table_name, operation, record_id, old_value, new_value)
        VALUES ('ACCOUNTS', 'DELETE', :OLD.account_id,
                'balance=' || :OLD.balance || '; status=' || :OLD.status,
