-- ----------------------------------------------------------------------------
-- 1. BRANCHES : physical bank locations.
-- ----------------------------------------------------------------------------
CREATE TABLE branches (
    branch_id     NUMBER GENERATED BY DEFAULT AS IDENTITY,
    branch_name   VARCHAR2(100)  NOT NULL,
    city          VARCHAR2(50)   NOT NULL,
    address       VARCHAR2(200),
    phone         VARCHAR2(20),
    created_at    DATE DEFAULT SYSDATE NOT NULL,
    CONSTRAINT pk_branches PRIMARY KEY (branch_id),
    CONSTRAINT uq_branch_name UNIQUE (branch_name)
);

-- ----------------------------------------------------------------------------
-- 2. EMPLOYEES : staff working at a branch.
-- ----------------------------------------------------------------------------
CREATE TABLE employees (
    employee_id   NUMBER GENERATED BY DEFAULT AS IDENTITY,
    branch_id     NUMBER,
    full_name     VARCHAR2(100)  NOT NULL,
    position      VARCHAR2(50),
    email         VARCHAR2(100),
    hire_date     DATE DEFAULT SYSDATE NOT NULL,
    salary        NUMBER(10,2),
    CONSTRAINT pk_employees PRIMARY KEY (employee_id),
    CONSTRAINT uq_employee_email UNIQUE (email),
    CONSTRAINT chk_emp_salary CHECK (salary >= 0),
    CONSTRAINT fk_emp_branch FOREIGN KEY (branch_id)
        REFERENCES branches (branch_id)
);

-- ----------------------------------------------------------------------------
-- 3. CUSTOMERS : people who hold accounts at the bank.
-- ----------------------------------------------------------------------------
CREATE TABLE customers (
    customer_id        NUMBER GENERATED BY DEFAULT AS IDENTITY,
    full_name          VARCHAR2(100)  NOT NULL,
    national_id        VARCHAR2(20)   NOT NULL,
    phone_number       VARCHAR2(20),
    email              VARCHAR2(100),
    date_of_birth      DATE,
    address            VARCHAR2(200),
    branch_id          NUMBER,
    registration_date  DATE DEFAULT SYSDATE NOT NULL,
    status             VARCHAR2(10) DEFAULT 'ACTIVE' NOT NULL,
    CONSTRAINT pk_customers PRIMARY KEY (customer_id),
    CONSTRAINT uq_customer_national_id UNIQUE (national_id),
    CONSTRAINT uq_customer_email UNIQUE (email),
    CONSTRAINT chk_customer_status CHECK (status IN ('ACTIVE','INACTIVE','CLOSED')),
    CONSTRAINT fk_cust_branch FOREIGN KEY (branch_id)
        REFERENCES branches (branch_id)
);

-- ----------------------------------------------------------------------------
-- 4. ACCOUNTS : bank accounts owned by customers.
--    balance carries a CHECK (>= 0) so the database itself forbids overdrafts.
-- ----------------------------------------------------------------------------
CREATE TABLE accounts (
    account_id      NUMBER GENERATED BY DEFAULT AS IDENTITY,
    account_number  VARCHAR2(20)   NOT NULL,
    customer_id     NUMBER         NOT NULL,
    account_type    VARCHAR2(20)   NOT NULL,
    balance         NUMBER(15,2) DEFAULT 0 NOT NULL,
    currency        VARCHAR2(3)  DEFAULT 'USD' NOT NULL,
    status          VARCHAR2(10) DEFAULT 'ACTIVE' NOT NULL,
    opened_date     DATE DEFAULT SYSDATE NOT NULL,
    CONSTRAINT pk_accounts PRIMARY KEY (account_id),
    CONSTRAINT uq_account_number UNIQUE (account_number),
    CONSTRAINT chk_account_type CHECK (account_type IN ('SAVINGS','CHECKING','CURRENT','FIXED')),
    CONSTRAINT chk_account_balance CHECK (balance >= 0),
    CONSTRAINT chk_account_status CHECK (status IN ('ACTIVE','FROZEN','CLOSED')),
    CONSTRAINT fk_acc_customer FOREIGN KEY (customer_id)
        REFERENCES customers (customer_id)
);

-- ----------------------------------------------------------------------------
-- 5. CARDS : debit/credit cards linked to an account.
-- ----------------------------------------------------------------------------
CREATE TABLE cards (
    card_id       NUMBER GENERATED BY DEFAULT AS IDENTITY,
    account_id    NUMBER         NOT NULL,
    card_number   VARCHAR2(20)   NOT NULL,
    card_type     VARCHAR2(10)   NOT NULL,
    expiry_date   DATE           NOT NULL,
    status        VARCHAR2(10) DEFAULT 'ACTIVE' NOT NULL,
    issued_date   DATE DEFAULT SYSDATE NOT NULL,
    CONSTRAINT pk_cards PRIMARY KEY (card_id),
    CONSTRAINT uq_card_number UNIQUE (card_number),
    CONSTRAINT chk_card_type CHECK (card_type IN ('DEBIT','CREDIT')),
    CONSTRAINT chk_card_status CHECK (status IN ('ACTIVE','BLOCKED','EXPIRED')),
    CONSTRAINT fk_card_account FOREIGN KEY (account_id)
        REFERENCES accounts (account_id)
);

-- ----------------------------------------------------------------------------
-- 6. LOANS : loans granted to customers.
-- ----------------------------------------------------------------------------
CREATE TABLE loans (
    loan_id              NUMBER GENERATED BY DEFAULT AS IDENTITY,
    customer_id          NUMBER         NOT NULL,
    loan_type            VARCHAR2(20)   NOT NULL,
    principal_amount     NUMBER(15,2)   NOT NULL,
    interest_rate        NUMBER(5,2)    NOT NULL,
    term_months          NUMBER(4)      NOT NULL,
    outstanding_balance  NUMBER(15,2),
    status               VARCHAR2(10) DEFAULT 'ACTIVE' NOT NULL,
    start_date           DATE DEFAULT SYSDATE NOT NULL,
    CONSTRAINT pk_loans PRIMARY KEY (loan_id),
    CONSTRAINT chk_loan_type CHECK (loan_type IN ('PERSONAL','HOME','AUTO','BUSINESS')),
    CONSTRAINT chk_loan_principal CHECK (principal_amount > 0),
    CONSTRAINT chk_loan_rate CHECK (interest_rate >= 0),
    CONSTRAINT chk_loan_term CHECK (term_months > 0),
    CONSTRAINT chk_loan_status CHECK (status IN ('ACTIVE','PAID','DEFAULT')),
    CONSTRAINT fk_loan_customer FOREIGN KEY (customer_id)
        REFERENCES customers (customer_id)
);

-- ----------------------------------------------------------------------------
-- 7. TRANSACTIONS : the money-movement ledger.
--    related_account_id is used for transfers (the "other side" of the move).
-- ----------------------------------------------------------------------------
CREATE TABLE transactions (
    transaction_id      NUMBER GENERATED BY DEFAULT AS IDENTITY,
    account_id          NUMBER         NOT NULL,
    transaction_type    VARCHAR2(20)   NOT NULL,
    amount              NUMBER(15,2)   NOT NULL,
    balance_after       NUMBER(15,2),
    related_account_id  NUMBER,
    description         VARCHAR2(200),
    transaction_date    TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT pk_transactions PRIMARY KEY (transaction_id),
    CONSTRAINT chk_txn_type CHECK (transaction_type IN
        ('DEPOSIT','WITHDRAWAL','TRANSFER_IN','TRANSFER_OUT')),
    CONSTRAINT chk_txn_amount CHECK (amount > 0),
    CONSTRAINT fk_txn_account FOREIGN KEY (account_id)
        REFERENCES accounts (account_id),
    CONSTRAINT fk_txn_related FOREIGN KEY (related_account_id)
        REFERENCES accounts (account_id)
);

-- ----------------------------------------------------------------------------
-- 8. AUDIT_LOGS : immutable audit trail written by triggers.
--    changed_by/CHANGE_DATE default automatically, so triggers stay simple.
-- ----------------------------------------------------------------------------
CREATE TABLE audit_logs (
    log_id        NUMBER GENERATED BY DEFAULT AS IDENTITY,
    table_name    VARCHAR2(30)   NOT NULL,
    operation     VARCHAR2(10)   NOT NULL,
    record_id     NUMBER,
    old_value     VARCHAR2(500),
    new_value     VARCHAR2(500),
    changed_by    VARCHAR2(50) DEFAULT USER NOT NULL,
    change_date   TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT pk_audit_logs PRIMARY KEY (log_id),
    CONSTRAINT chk_audit_operation CHECK (operation IN ('INSERT','UPDATE','DELETE'))
);

