-- ============================================================================
-- File   : 02_create_tables.sql
-- Purpose: Create the full banking schema (tables, constraints, sequence).
-- Engine : Oracle Database (Oracle XE 21c / SQL Developer)
-- Order  : Tables are created parent-first so foreign keys always resolve.
